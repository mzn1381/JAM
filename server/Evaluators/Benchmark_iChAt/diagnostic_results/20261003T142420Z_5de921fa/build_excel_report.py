def excel_value(v):
    if isinstance(v, (dict, list)):
        return json.dumps(v, ensure_ascii=False)
    if v is None:
        return ""
    return v


def add_sheet(name, headers, rows, widths=None):
    ws = wb.create_sheet(name)
    ws.sheet_view.rightToLeft = True
    ws.sheet_view.zoomScale = 85
    ws.freeze_panes = "A2"
    ws.append(headers)

    for row in rows:
        ws.append([excel_value(v) for v in row])

    for c in ws[1]:
        c.fill = PatternFill("solid", fgColor=NAVY)
        c.font = Font(name="Tahoma", size=11, bold=True, color=WHITE)
        c.alignment = Alignment(
            horizontal="right", vertical="center",
            wrap_text=True, readingOrder=2
        )

    ws.row_dimensions[1].height = 34

    for row in ws.iter_rows(min_row=2):
        for c in row:
            # داده‌های ورودی باید متن باشند، نه فرمول Excel.
            if isinstance(c.value, str):
                c.data_type = "s"
            c.font = Font(name="Tahoma", size=10)
            c.alignment = Alignment(
                horizontal="right", vertical="top",
                wrap_text=True, readingOrder=2
            )
            c.border = Border(bottom=thin)
            if c.row % 2 == 0:
                c.fill = PatternFill("solid", fgColor=GRAY)
            if isinstance(c.value, str) and c.value in STATUS_COLORS:
                c.fill = PatternFill(
                    "solid", fgColor=STATUS_COLORS[c.value]
                )
                c.font = Font(name="Tahoma", size=10, bold=True)

    widths = widths or [28] * len(headers)
    for i, width in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = width

    # برآورد ارتفاع سطر برای خوانایی؛ متن کامل در سلول حفظ می‌شود.
    for row in ws.iter_rows(min_row=2):
        lines = 1
        for c in row:
            width = widths[c.column - 1]
            text = str(c.value or "")
            estimated = sum(
                max(1, math.ceil(len(part) / max(10, width * 0.9)))
                for part in text.split("\n")
            )
            lines = max(lines, estimated)
        ws.row_dimensions[row[0].row].height = min(
            360, max(32, 17 * lines + 10)
        )

    ws.auto_filter.ref = ws.dimensions
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    ws.page_setup.orientation = "landscape"
    ws.page_setup.paperSize = ws.PAPERSIZE_A3
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.print_title_rows = "1:1"
    return ws


def percentile_inc(values, p):
    values = sorted(values)
    position = (len(values) - 1) * p
    low = math.floor(position)
    high = math.ceil(position)
    return values[low] + (
        values[high] - values[low]
    ) * (position - low)


